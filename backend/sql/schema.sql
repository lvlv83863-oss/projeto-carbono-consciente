-- =====================================================================
-- Banco de Dados: Carbono Consciente (PostgreSQL / Supabase)
-- Descrição: Estrutura para cadastro de usuários e registro de hábitos
--            de deslocamento com cálculo de pegada de carbono (CO2)
--
-- Este arquivo pode ser executado várias vezes sem erro (usa IF NOT EXISTS,
-- ON CONFLICT DO NOTHING, DROP TRIGGER IF EXISTS e CREATE OR REPLACE).
-- Para aplicá-lo: cole no SQL Editor do Supabase e clique em Run,
-- ou pelo terminal:  cd backend && npm run db:setup
--
-- Observações da versão PostgreSQL:
--  * Não existe CREATE DATABASE / USE aqui: o banco já é criado pelo Supabase.
--  * AUTO_INCREMENT virou GENERATED BY DEFAULT AS IDENTITY.
--  * DATETIME virou TIMESTAMP.
--  * ON UPDATE CURRENT_TIMESTAMP virou trigger (fn_atualiza_atualizado_em).
--  * INSERT IGNORE virou INSERT ... ON CONFLICT DO NOTHING.
--  * O código "pais" guarda o ISO_A3 do país (ex.: 'BRA'); campo opcional.
-- =====================================================================

-- ---------------------------------------------------------------------
-- Tabela: usuarios
-- Armazena os dados cadastrais da pessoa
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS usuarios (
    id_usuario      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome            VARCHAR(150) NOT NULL,
    email           VARCHAR(150) NOT NULL UNIQUE,
    senha_hash      VARCHAR(255) NOT NULL,
    pais            VARCHAR(80)  DEFAULT NULL,
    criado_em       TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    atualizado_em   TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- ---------------------------------------------------------------------
-- Trigger: atualiza "atualizado_em" a cada UPDATE em usuarios
-- (substitui o ON UPDATE CURRENT_TIMESTAMP do MySQL)
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_atualiza_atualizado_em()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
    NEW.atualizado_em := CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_usuarios_atualizado_em ON usuarios;

CREATE TRIGGER trg_usuarios_atualizado_em
BEFORE UPDATE ON usuarios
FOR EACH ROW
EXECUTE FUNCTION fn_atualiza_atualizado_em();

-- ---------------------------------------------------------------------
-- Tabela: meios_transporte
-- Lista de meios de transporte e o fator de emissão de CO2 (kg/km)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS meios_transporte (
    id_meio         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome            VARCHAR(80) NOT NULL UNIQUE,
    fator_emissao   DECIMAL(6,4) NOT NULL,
    icone           VARCHAR(10) DEFAULT NULL
);

COMMENT ON COLUMN meios_transporte.fator_emissao IS 'kg de CO2 por km percorrido';

