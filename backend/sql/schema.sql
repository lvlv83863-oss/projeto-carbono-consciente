-- ---------------------------------------------------------------------
-- Tabela: habitos
-- Cada linha é um registro de deslocamento feito pelo usuário
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS habitos (
    id_habito       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario      INT NOT NULL,
    id_meio         INT NOT NULL,
    data_registro   DATE NOT NULL,
    distancia_km    DECIMAL(8,2) NOT NULL,
    co2_emitido_kg  DECIMAL(10,3) NOT NULL,
    observacao      VARCHAR(255) DEFAULT NULL,
    criado_em       TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_habitos_usuario
        FOREIGN KEY (id_usuario) REFERENCES usuarios(id_usuario)
        ON DELETE CASCADE,

    CONSTRAINT fk_habitos_meio
        FOREIGN KEY (id_meio) REFERENCES meios_transporte(id_meio)
        ON DELETE RESTRICT,

    CONSTRAINT chk_distancia_positiva CHECK (distancia_km >= 0)
);

COMMENT ON COLUMN habitos.co2_emitido_kg IS 'distancia_km * fator_emissao';

-- Índice para acelerar as consultas usadas nos cards
-- (hoje vs ontem, semana vs anterior, mês vs anterior)
CREATE INDEX IF NOT EXISTS idx_habitos_usuario_data
    ON habitos (id_usuario, data_registro);

-- ---------------------------------------------------------------------
-- Trigger: calcula automaticamente o CO2 emitido ao inserir um hábito
-- (caso o valor não seja enviado pela aplicação ou seja 0)
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_habitos_calcula_co2()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
    IF NEW.co2_emitido_kg IS NULL OR NEW.co2_emitido_kg = 0 THEN
        NEW.co2_emitido_kg := NEW.distancia_km *
            (SELECT fator_emissao FROM meios_transporte WHERE id_meio = NEW.id_meio);
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_habitos_calcula_co2 ON habitos;

CREATE TRIGGER trg_habitos_calcula_co2
BEFORE INSERT ON habitos
FOR EACH ROW
EXECUTE FUNCTION fn_habitos_calcula_co2();

-- ---------------------------------------------------------------------
-- View: resumo diário de emissões por usuário
-- Útil para alimentar os cards "Diário / Semanal / Mensal" do painel
-- ---------------------------------------------------------------------
CREATE OR REPLACE VIEW vw_emissoes_diarias AS
SELECT
    h.id_usuario,
    h.data_registro,
    SUM(h.co2_emitido_kg) AS total_co2_dia
FROM habitos h
GROUP BY h.id_usuario, h.data_registro;

-- ---------------------------------------------------------------------
-- Segurança (Supabase)
-- O Supabase expõe as tabelas do schema "public" por uma API REST.
-- Ligando o RLS (Row Level Security) sem criar políticas, essa API não
-- consegue ler nem escrever nada. O seu back conecta com o usuário
-- "postgres" (string do pooler), que ignora o RLS, então continua
-- funcionando normalmente.
-- ---------------------------------------------------------------------
ALTER TABLE usuarios         ENABLE ROW LEVEL SECURITY;
ALTER TABLE meios_transporte ENABLE ROW LEVEL SECURITY;
ALTER TABLE habitos          ENABLE ROW LEVEL SECURITY;

-- A view passa a respeitar o RLS de quem consulta
ALTER VIEW vw_emissoes_diarias SET (security_invoker = true);

